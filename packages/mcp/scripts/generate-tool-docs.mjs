/* Generates docs/tools.md from the live zod schemas, so the reference can't
 * drift from the tools the server actually exposes.
 *
 * Run: pnpm docs:tools (chained from pnpm build)
 */
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'

import { recipes } from '../dist/recipes/index.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Shared options documented once in output-types.md rather than 16 times */
const COMMON = new Set([
  'width', 'height', 'theme', 'title', 'colors',
  'outputType', 'outputPath', 'scale', 'framework', 'locale',
])

const escape = (text) => String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n+/g, ' ')

/** Human-readable type for a zod schema, unwrapping optional/default layers */
function typeOf (schema) {
  const def = schema?._def
  if (!def) return 'unknown'
  switch (def.typeName) {
    case 'ZodOptional':
    case 'ZodDefault':
      return typeOf(def.innerType)
    case 'ZodString': return 'string'
    case 'ZodNumber': return 'number'
    case 'ZodBoolean': return 'boolean'
    case 'ZodEnum': return def.values.map(v => `\`${v}\``).join(' \\| ')
    case 'ZodArray': return `${typeOf(def.type)}[]`
    case 'ZodUnion': return def.options.map(typeOf).join(' \\| ')
    case 'ZodTuple': return `[${def.items.map(typeOf).join(', ')}]`
    case 'ZodRecord': return 'object'
    case 'ZodObject': {
      const shape = def.shape()
      return `{ ${Object.keys(shape).join(', ')} }`
    }
    default: return 'unknown'
  }
}

function defaultOf (schema) {
  let def = schema?._def
  while (def) {
    if (def.typeName === 'ZodDefault') {
      const value = def.defaultValue()
      return value === '' ? '`""`' : `\`${JSON.stringify(value)}\``
    }
    def = def.innerType?._def
  }
  return schema?.isOptional?.() ? '—' : '**required**'
}

const describe = (schema) => schema?._def?.description ??
  schema?._def?.innerType?._def?.description ??
  schema?._def?.innerType?._def?.innerType?._def?.description ?? ''

function optionRows (shape) {
  const rows = []
  for (const [name, schema] of Object.entries(shape)) {
    if (COMMON.has(name)) continue
    rows.push(`| \`${name}\` | ${typeOf(schema)} | ${defaultOf(schema)} | ${escape(describe(schema))} |`)
  }
  return rows
}

const sections = recipes.map(recipe => {
  const rows = optionRows(recipe.inputShape)
  return `### \`${recipe.name}\`

${recipe.description}

| Option | Type | Default | Description |
|---|---|---|---|
${rows.join('\n')}
`
})

const content = `# Tools reference

<!-- Generated by scripts/generate-tool-docs.mjs — run \`pnpm docs:tools\` after changing a recipe. -->

Every chart tool takes \`data\` as an array of flat records plus field-name
accessors, and shares the options documented in
[Output types](./output-types.md#shared-options): \`width\`, \`height\`,
\`theme\`, \`title\`, \`colors\`, \`locale\`, \`outputType\`, \`outputPath\`, \`scale\`
and \`framework\`.

Tools can be hidden per deployment with \`DISABLED_TOOLS\` or \`--tools\`
(see [Getting started](./getting-started.md#limiting-the-tool-surface)).

## Chart tools

${sections.join('\n')}
## \`get_unovis_info\`

Returns server capabilities: the active tool list, supported themes, output
types, frameworks and the default color palette. Useful for a client (or an
agent) to discover what this deployment can do before calling anything.
`

const target = join(root, 'docs', 'tools.md')
writeFileSync(target, content)
console.error(`✓ wrote ${target} (${recipes.length} chart tools)`)
