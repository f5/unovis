import { test, expect } from '@playwright/test'

test('circular bar controls reflect direct overrides and can replace them with presets', async ({ page }, testInfo) => {
  const config = { circularBar: { innerRadius: 120.5, barPadding: 42.5, angleRange: [0.2, 2.5] }, line: { lineWidth: 7 } }
  await page.goto(`/examples/Circular%20Bar/Circular%20Bar%20Playground?capture=1&config=${encodeURIComponent(JSON.stringify(config))}`)
  const frame = page.getByTestId('example-capture')
  await expect(frame).toHaveAttribute('data-capture-ready', 'true')
  await frame.screenshot({ path: testInfo.outputPath('initial.png') })
  const radius = page.getByRole('slider', { name: 'innerRadius', exact: true })
  await expect(radius).toBeEnabled()
  await expect(radius).toHaveValue('120.5')
  await expect(page.getByRole('slider', { name: 'barPadding', exact: true })).toHaveValue('42.5')
  await expect(page.getByLabel(/^angleRange/)).toHaveValue('custom')
  await radius.press('Home')
  await expect(radius).toHaveValue('0')
  await expect.poll(() => JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}').circularBar?.innerRadius).toBeUndefined()
  await page.getByLabel(/^angleRange/).selectOption('Top half')
  await page.reload()
  await expect(radius).toHaveValue('0')
  await expect(page.getByLabel(/^angleRange/)).toHaveValue('Top half')
  await expect(page.locator('input[type="checkbox"]').first()).not.toBeChecked()
  await page.locator('input[type="checkbox"]').first().check()
  await expect(radius).toBeDisabled()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(radius).toHaveValue('52')
  await expect(radius).toBeDisabled()
  expect(JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}')).toEqual({ line: config.line })
})

for (const name of ['plotline', 'plotband']) {
  test(`${name} bleed controls expose overrides and restore their preset behavior`, async ({ page }) => {
    test.setTimeout(60000)
    const group = name === 'plotline' ? 'Plotline' : 'Plotband'
    const config = { [name]: { labelText: 'Direct label', value: 3, from: 1, to: 2 }, line: { lineWidth: 7 } }
    await page.goto(`/examples/${group}/${group}%20Label%20Bleed?capture=1&config=${encodeURIComponent(JSON.stringify(config))}`)
    const text = page.getByLabel('Label Text:', { exact: true })
    const preset = page.getByLabel(name === 'plotline' ? /^Plotline Value:/ : /^Plotband Extent:/)
    await expect(text).toHaveValue('Direct label')
    await expect(preset).toHaveValue('custom')
    await text.fill('Edited label')
    await preset.selectOption('domain start')
    await expect.poll(() => JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}')[name]?.labelText).toBeUndefined()
    await page.reload()
    await expect(text).toHaveValue('Edited label')
    await expect(preset).toHaveValue('domain start')
    await expect(page.locator('svg').getByText('Edited label', { exact: true }).first()).toBeVisible()
    const current = JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}')
    expect(current.line).toEqual(config.line)
    expect(name === 'plotline' ? current[name]?.value : current[name]?.from).toBeUndefined()
  })
}

test('derived toggles replace label overrides without losing unrelated config', async ({ page }) => {
  const config = { nestedDonut: { hideOverflowingSegmentLabels: true }, scatter: { label: 'Direct label' }, line: { lineWidth: 7 } }
  await page.goto(`/examples/Nested%20Donut/Segment%20labels?capture=1&config=${encodeURIComponent(JSON.stringify(config))}`)
  await page.getByRole('button', { name: 'Show Labels', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Hide Labels', exact: true })).toBeVisible()
  expect(JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}').nestedDonut).toBeUndefined()
  await page.goto(`/examples/Scatter/Point%20Label%20Positions?capture=1&config=${encodeURIComponent(JSON.stringify(config))}`)
  const toggle = page.getByLabel('Labels:', { exact: true })
  await expect(toggle).toBeChecked()
  await expect(page.locator('svg').getByText('Direct label', { exact: true }).first()).toBeVisible()
  await toggle.uncheck()
  await expect(page.locator('svg').getByText('Direct label', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(toggle).not.toBeChecked()
  expect(JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}')).toEqual({ nestedDonut: config.nestedDonut, line: config.line })
})

test('function presets can replace explicit default overrides', async ({ page }) => {
  await page.goto(`/examples/Nested%20Donut/Segment%20values?capture=1&config=${encodeURIComponent(JSON.stringify({ nestedDonut: { sort: null }, example: { sortIndex: 2 } }))}`)
  const preset = page.locator('select').first()
  await expect(preset).toHaveValue('custom')
  await preset.selectOption('1')
  await page.reload()
  await expect(preset).toHaveValue('1')
  expect(JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}').nestedDonut).toBeUndefined()
  await page.goto(`/examples/Treemap/Treemap%3A%20Tiling%20Methods?capture=1&config=${encodeURIComponent(JSON.stringify({ treemap: { tileFunction: null } }))}`)
  await expect(preset).toHaveValue('custom')
  await preset.selectOption('dice')
  await page.reload()
  await expect(preset).toHaveValue('dice')
  expect(JSON.parse(new URL(page.url()).searchParams.get('config') ?? '{}').treemap).toBeUndefined()
})
